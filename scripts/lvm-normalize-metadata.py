#!/usr/bin/env python3
"""Rewrite the LVM2 metadata of a physical volume so that it depends only on
the volume group's configuration and on SOURCE_DATE_EPOCH.

usage: lvm-normalize-metadata.py IMAGE PV_OFFSET_IN_BYTES

LVM writes, into the text metadata stored on the disk, the name of the build
host and its kernel version, the time of each change, and the name of the
device (a loop device during the build). It also keeps the previous versions
of the metadata in the metadata area. This tool keeps one copy of the current
metadata, with these values replaced, and updates the two checksums.

Only the metadata area is written. The label and the header of the physical
volume are checked, and left as pvcreate wrote them.
"""

import os
import re
import struct
import sys
import time
import zlib

SECTOR = 512
MDA_HEADER_SIZE = 512
MDA_MAGIC = b" LVM2 x[5A%r0N*>"
INITIAL_CRC = 0xF597A6CF


def crc(data):
    """LVM's calc_crc(): CRC-32 without the initial and final inversions of zlib."""
    return (zlib.crc32(data, INITIAL_CRC ^ 0xFFFFFFFF) ^ 0xFFFFFFFF) & 0xFFFFFFFF


def die(msg):
    sys.exit(f"lvm-normalize-metadata: {msg}")


def main():
    image, pv_offset = sys.argv[1], int(sys.argv[2])
    epoch = int(os.environ["SOURCE_DATE_EPOCH"])

    with open(image, "r+b") as f:
        # label: in one of the first four sectors of the physical volume
        f.seek(pv_offset)
        head = f.read(4 * SECTOR)
        for n in range(4):
            label = head[n * SECTOR:(n + 1) * SECTOR]
            if label[:8] == b"LABELONE":
                break
        else:
            die("no LVM label found")
        sector, label_crc, contents_offset, label_type = struct.unpack_from("<QII8s", label, 8)
        if label_type != b"LVM2 001" or sector != n or crc(label[20:]) != label_crc:
            die("unexpected LVM label")

        # header of the physical volume: UUID, size, data areas, metadata areas
        pos = contents_offset + 40
        areas = [[], []]
        for kind in areas:
            while True:
                offset, size = struct.unpack_from("<QQ", label, pos)
                pos += 16
                if offset == 0:
                    break
                kind.append((offset, size))
        if len(areas[1]) != 1:
            die(f"{len(areas[1])} metadata areas, expected 1")
        mda_offset, mda_size = areas[1][0]

        # header of the metadata area, and the current metadata text
        f.seek(pv_offset + mda_offset)
        mda = f.read(mda_size)
        header = bytearray(mda[:MDA_HEADER_SIZE])
        checksum, magic, version, start, size = struct.unpack_from("<I16sIQQ", header, 0)
        if magic != MDA_MAGIC or version != 1 or (start, size) != (mda_offset, mda_size):
            die("unexpected header of the metadata area")
        if crc(bytes(header[4:])) != checksum:
            die("wrong checksum of the header of the metadata area")
        text_offset, text_size, text_crc, flags = struct.unpack_from("<QQII", header, 40)
        if text_offset + text_size <= mda_size:
            raw = mda[text_offset:text_offset + text_size]
        else:  # the metadata area is a ring buffer
            first = mda_size - text_offset
            raw = mda[text_offset:] + mda[MDA_HEADER_SIZE:MDA_HEADER_SIZE + text_size - first]
        if crc(raw) != text_crc:
            die("wrong checksum of the metadata text")
        text = raw.rstrip(b"\0")
        padding = len(raw) - len(text)

        # the values that depend on the build host and on the build time
        date = time.strftime("%a %b %e %H:%M:%S %Y", time.gmtime(epoch)).encode()
        rules = [
            (rb"^(# Generated by LVM2 version [^:]*: ).*$", rb"\g<1>" + date),
            (rb"^(\s*description = ).*$", rb'\g<1>""'),
            (rb"^(\s*creation_host = ).*$", rb'\g<1>"seapath"'),
            (rb"^(\s*creation_time = ).*$", rb"\g<1>" + str(epoch).encode()),
            (rb"^(\s*device = ).*$", rb'\g<1>"[unknown]"'),
        ]
        for pattern, replacement in rules:
            text, count = re.subn(pattern, replacement, text, flags=re.M)
            if count == 0:
                die(f"no line matches {pattern.decode()}")
        raw = text + b"\0" * padding
        if MDA_HEADER_SIZE + len(raw) > mda_size:
            die("metadata too large")

        # one copy of the metadata, right after the header; no older copies
        struct.pack_into("<QQII", header, 40, MDA_HEADER_SIZE, len(raw), crc(raw), flags)
        header[64:] = bytes(MDA_HEADER_SIZE - 64)
        struct.pack_into("<I", header, 0, crc(bytes(header[4:])))
        f.seek(pv_offset + mda_offset)
        f.write(bytes(header) + raw + bytes(mda_size - MDA_HEADER_SIZE - len(raw)))

    print(f"LVM metadata normalized: {len(text)} bytes of text, metadata area of {mda_size} bytes")


if __name__ == "__main__":
    main()
